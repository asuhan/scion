struct LineSelection {
  static func logicalTop(lineBox: InlineIterator.LineBox) -> Float32 {
    return lineBox.contentLogicalTopAdjustedForPrecedingLineBox()
  }

  static func logicalBottom(lineBox: InlineIterator.LineBox) -> Float32 {
    return lineBox.contentLogicalBottomAdjustedForFollowingLineBox()
  }

  static func logicalRect(lineBox: InlineIterator.LineBox) -> FloatRectWrapper {
    return FloatRectWrapper(
      topLeft: FloatPoint(
        x: lineBox.contentLogicalLeft(), y: lineBox.contentLogicalTopAdjustedForPrecedingLineBox()),
      bottomRight: FloatPoint(
        x: lineBox.contentLogicalRight(),
        y: lineBox.contentLogicalBottomAdjustedForFollowingLineBox()))
  }
}

// Generated by Tools/Scripts/scion-translate.
extension LineSelection {
  static func physicalRect(lineBox: InlineIterator.LineBox) -> FloatRectWrapper {
    var physicalRect = LineSelection.logicalRect(lineBox: lineBox)
    if !lineBox.isHorizontal() {
      physicalRect = physicalRect.transposedRect()
    }
    lineBox.formattingContextRoot().flipForWritingMode(rect: &physicalRect)
    return physicalRect
  }

  static func logicalTopAdjustedForPrecedingBlock(lineBox: InlineIterator.LineBox) -> Float32 {
    // FIXME: Move adjustEnclosingTopForPrecedingBlock from RenderBlockFlow to here.
    return
      (lineBox.formattingContextRoot().adjustEnclosingTopForPrecedingBlock(
        top: LayoutUnit(value: Float64(lineBox.contentLogicalTopAdjustedForPrecedingLineBox()))))
      .toFloat()
    // FIXME: Move adjustEnclosingTopForPrecedingBlock from RenderBlockFlow to here.
  }

  static func selectionState(lineBox: InlineIterator.LineBox) -> RenderObjectWrapper.HighlightState
  {
    let root = lineBox.formattingContextRoot()
    if root.selectionState() == .None {
      return .None
    }
    var lineState: RenderObjectWrapper.HighlightState = .None
    let box = lineBox.firstLeafBox()
    while box.bool() {
      let boxState = box.get().selectionState()
      if lineState == .None {
        lineState = boxState
      } else if lineState == .Start {
        if boxState == .End || boxState == .None {
          lineState = .Both
        }
      } else if lineState == .Inside {
        if boxState == .Start || boxState == .End {
          lineState = boxState
        } else if boxState == .None {
          lineState = .End
        }
      } else if lineState == .End {
        if boxState == .Start {
          lineState = .Both
        }
      }
      if lineState == .Both {
        break
      }
      box.traverseNextOnLine()
    }
    return lineState
  }

}
